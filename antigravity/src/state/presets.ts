export function getAllPresets(): Preset[] {
  return [...FACTORY_PRESETS, ...loadUserPresets()];
}

export function getPresetById(id: string): Preset | undefined {
  return getAllPresets().find((p) => p.id === id);
}

export function createUserPreset(name: string, description: string, params: ParamMap): Preset {
  const existing = loadUserPresets();
  const slug = name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "") || "custom";
  const preset: Preset = {
    id: `user-${slug}-${Date.now().toString(36)}`,
    name: name.trim() || "Custom Patch",
    description: description.trim() || "Saved user synthesizer patch",
    category: "User",
    params: { ...params },
  };
  saveUserPresets([...existing, preset]);
  return preset;
}

export function deleteUserPreset(id: string): boolean {
  const existing = loadUserPresets();
  const next = existing.filter((p) => p.id !== id);
  if (next.length === existing.length) return false;
  saveUserPresets(next);
  return true;
}
