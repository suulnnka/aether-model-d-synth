const fmtFixed1 = (v: number) => v.toFixed(1);
const fmtSemi = (v: number) => `${v >= 0 ? "+" : ""}${v.toFixed(1)} st`;
const fmtPct = (v: number) => `${Math.round(v)}%`;
const fmtHz = (v: number) => {
  const hz = mapCutoff(v);
  return hz >= 1000 ? `${(hz / 1000).toFixed(2)} kHz` : `${Math.round(hz)} Hz`;
};
const fmtEnv = (v: number) => {
  const s = mapEnvelopeTime(v);
  return s >= 1 ? `${s.toFixed(2)} s` : `${Math.round(s * 1000)} ms`;
};

