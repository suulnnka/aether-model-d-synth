export const SPEC_BY_ID: Record<ControlId, ControlSpec> = CONTROL_SPECS.reduce(
  (acc, spec) => {
    acc[spec.id] = spec;
    return acc;
  },
  {} as Record<ControlId, ControlSpec>,
);

export function createDefaultParams(): ParamMap {
  const map = {} as ParamMap;
  for (const spec of CONTROL_SPECS) {
    map[spec.id] = spec.defaultValue;
  }
  return map;
}

export function clampControlValue(id: ControlId, value: number): number {
  const spec = SPEC_BY_ID[id];
  if (!Number.isFinite(value)) return spec.defaultValue;
  const clamped = Math.max(spec.min, Math.min(spec.max, value));
  if (spec.kind === "switch" || spec.kind === "step") {
    return Math.round(clamped);
  }
  return clamped;
}

export function formatControlValue(id: ControlId, value: number): string {
  const spec = SPEC_BY_ID[id];
  if (spec.kind === "switch" && spec.switchLabels) {
    return value >= 0.5 ? spec.switchLabels[1] : spec.switchLabels[0];
  }
  if (spec.kind === "step" && spec.stepLabels) {
    const idx = Math.max(0, Math.min(spec.stepLabels.length - 1, Math.round(value)));
    return spec.stepLabels[idx];
  }
  if (spec.format) return spec.format(value);
  return value.toFixed(1);
}
